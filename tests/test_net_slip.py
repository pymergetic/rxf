"""Pins for the SLIP line (docs/25 §13) — RFC 1055 byte-exact and every open policy
named and pinned.

The protocol source of record is RFC 1055 (Romkey, June 1988); the byte-exact cases
cite its PROTOCOL and SLIP DRIVERS sections (the reference `send_packet`/`recv_packet`
and Karn's leading-END change). The policies RFC 1055 leaves open are decided by name
in `slip.py`'s module docstring and pinned here: the empty-frame skip, the malformed
drop for an escape truncated by the frame's end, the best-bet literal stuffing, the
half-frame noise discard, the no-guess rule for END-delimited garbage, the overrun
drop, the empty-payload refusal, and one error count per dropped frame. The device
gates pin the §13 line contract (open/close, TX, RX readiness, MTU, counters) over the
in-memory fill, both directions.
"""

