def test_the_special_characters_are_the_rfcs_octal_values() -> None:
    """The four constants are the RFC's `#define`s (RFC 1055, SLIP DRIVERS): END is
    octal 300 (decimal 192), ESC octal 333 (219) — "not to be confused with the ASCII
    ESCape character" — ESC_END octal 334 (220), ESC_ESC octal 335 (221)."""
    assert (END, ESC, ESC_END, ESC_ESC) == (0o300, 0o333, 0o334, 0o335)
    assert (END, ESC, ESC_END, ESC_ESC) == (192, 219, 220, 221)


def test_encoding_is_the_rfcs_send_packet_byte_for_byte() -> None:
    """`encode` is the reference `send_packet` (RFC 1055, SLIP DRIVERS): "send an
    initial END character to flush out any data that may have accumulated in the
    receiver due to line noise", END goes out as ESC ESC_END and ESC as ESC ESC_ESC,
    and "When the last byte in the packet has been sent, an END character is then
    transmitted." — quoted from RFC 1055, SLIP DRIVERS."""
    assert encode(b"A") == b"\xc0A\xc0"
    assert encode(bytes((END,))) == b"\xc0\xdb\xdc\xc0"
    assert encode(bytes((ESC,))) == b"\xc0\xdb\xdd\xc0"
    assert encode(bytes((END, ESC))) == b"\xc0\xdb\xdc\xdb\xdd\xc0"


def test_only_end_and_esc_are_ever_stuffed() -> None:
    """RFC 1055, PROTOCOL stuffs exactly two bytes: "If a data byte is the same code
    as END character ... If it the same as an ESC character ...". ESC_END and ESC_ESC
    as payload bytes are ordinary data and ride bare — the stuffing is not a
    four-byte alphabet."""
    assert encode(bytes((ESC_END, ESC_ESC))) == b"\xc0\xdc\xdd\xc0"


def test_decoding_is_the_rfcs_recv_packet_byte_for_byte() -> None:
    """The unstuffed pairs come back as their data bytes (RFC 1055, PROTOCOL): "a two
    byte sequence of ESC and octal 334 ... ESC and octal 335", and the initial END of
    Karn's change syncs without emitting anything."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0\xdb\xdc\xdb\xdd\xc0") == (bytes((END, ESC)),)


def test_the_duplicate_end_quirk_skips_empty_frames() -> None:
    """A bare END ends the frame in progress and empty frames between ENDs are never
    emitted — the reference `recv_packet`'s own "minor optimization" (RFC 1055, SLIP
    DRIVERS): "if there is no data in the packet, ignore it. This is meant to avoid
    bothering IP with all the empty packets generated by the duplicate END characters
    which are in turn sent to try to detect line noise." Not an error: no counter
    moves."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0\xc0\xc0A\xc0\xc0") == (b"A",)
    assert decoder.counters == SlipCounters(framing=0, overrun=0)


def test_the_rfcs_best_bet_stuffing_is_kept() -> None:
    """ESC + a byte that is neither escape code is a "protocol violation" the
    reference receiver absorbs (RFC 1055, SLIP DRIVERS): "The best bet seems to be to
    leave the byte alone and just stuff it into the packet" — kept, pinned byte-exact,
    quirks included."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0X\x41Y\xc0") == (b"XAY",)
    assert decoder.counters == SlipCounters(framing=0, overrun=0)


def test_roundtrip_is_total_over_arbitrary_packets() -> None:
    """encode/decode roundtrips arbitrary packets — all four special bytes in play
    (END and ESC stuffed, ESC_END and ESC_ESC bare), every length from one byte up.
    The domain excludes the empty payload, whose refusal is pinned separately."""
    rng = random.Random(1055)
    forced = bytes((END, ESC, ESC_END, ESC_ESC))
    for _ in range(128):
        length = rng.randrange(1, 300)
        payload = forced + bytes(rng.randrange(256) for _ in range(length))
        assert SlipDecoder().feed(encode(payload)) == (payload,)
    assert SlipDecoder().feed(encode(forced * 64)) == (forced * 64,)


def test_an_empty_payload_is_refused_at_every_face() -> None:
    """The pinned empty-payload policy (slip.py's module docstring): the reference
    `send_packet` would frame a zero-length packet as `END END`, which every receiver
    discards — bytes the protocol guarantees to throw away are a silent no-op, so the
    codec and the line refuse `NotSupported` instead. The receive-side quirk lives
    where the RFC put it: END END delivers nothing."""
    with pytest.raises(NotSupported):
        encode(b"")
    encoder = SlipEncoder()
    with pytest.raises(NotSupported):
        encoder.finish()  # a frame with nothing fed is an empty frame
    line = SlipLine()
    line.open()
    line.set_knob("net/dev/slip0", Knob.LINK, LinkState.UP)
    with pytest.raises(NotSupported):
        line.write(b"")
    assert SlipDecoder().feed(b"\xc0\xc0") == ()


def test_a_frame_arriving_byte_by_byte_is_never_half_emitted() -> None:
    """Split-buffer pin and the named quirk: the decoder never emits a half frame —
    a frame arriving one byte at a time is answered exactly once, complete, at its
    closing END."""
    decoder = SlipDecoder()
    line = encode(b"hello")
    frames: list[bytes] = []
    for index in range(len(line)):
        out = decoder.feed(line[index : index + 1])
        if index < len(line) - 1:
            assert out == ()  # nothing until the closing END
        else:
            assert out == (b"hello",)
        frames.extend(out)
    assert tuple(frames) == (b"hello",)


def test_random_chunk_splits_never_change_the_parse() -> None:
    """Split-buffer property: whatever chunk sizes the wire delivers, the decoder
    answers the same packets — chunking never changes the parse."""
    rng = random.Random(2024)
    for _ in range(50):
        payload = bytes(rng.randrange(256) for _ in range(rng.randrange(1, 200)))
        line = encode(payload)
        decoder = SlipDecoder()
        frames: list[bytes] = []
        at = 0
        while at < len(line):
            take = rng.randrange(1, 8)
            frames.extend(decoder.feed(line[at : at + take]))
            at += take
        assert tuple(frames) == (payload,)


def test_an_escape_split_across_feeds_still_unstuffs() -> None:
    """The split-buffer pin at the tightest seam: the ESC and its follower arriving
    in different chunks still unstuff to their data byte."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0ab\xdb") == ()
    assert decoder.feed(b"\xdc\xc0") == (b"ab\xc0",)


def test_the_streaming_encoder_matches_the_whole_packet_face() -> None:
    """Split-buffer pin on TX: a packet fed in pieces stuffs byte-identically to the
    whole-packet face — one codec, whatever chunks arrive."""
    payload = b"a\xc0b\xdbc" * 5
    encoder = SlipEncoder()
    line = bytearray()
    for index in range(0, len(payload), 3):
        line += encoder.feed(payload[index : index + 3])
    line += encoder.finish()
    assert bytes(line) == encode(payload)


def test_a_truncated_escape_drops_the_frame_and_counts_framing() -> None:
    """ESC as the frame's final byte is a malformed frame — the pinned policy
    (slip.py's module docstring): dropped whole, never half-emitted, one `framing`,
    and the END stays the boundary for what follows. The reference `recv_packet`
    would stuff the END byte literally and swallow the boundary with it; a guessed
    byte is a wrong parse half-applied (docs/25 §12) and is refused here."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0ab\xdb\xc0") == ()
    assert decoder.counters == SlipCounters(framing=1, overrun=0)
    assert decoder.feed(b"\xc0ok\xc0") == (b"ok",)
    assert decoder.counters == SlipCounters(framing=1, overrun=0)


def test_a_truncated_escape_across_feeds_gets_the_same_policy() -> None:
    """The malformed policy is a wire policy, not a chunking accident: the same ESC
    END split across two feeds drops and counts exactly the same way."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0ab\xdb") == ()
    assert decoder.feed(b"\xc0") == ()
    assert decoder.counters == SlipCounters(framing=1, overrun=0)


def test_a_bare_end_ends_the_frame_and_syncs() -> None:
    """A bare END ends the frame in progress and syncs the line — Karn's change
    (RFC 1055, PROTOCOL): "This will flush any erroneous bytes which have been caused
    by line noise" — and frames appear only at an END."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0") == ()  # the leading END: syncs, no frame
    assert decoder.feed(b"ab") == ()  # frame content: a boundary is behind it
    assert decoder.feed(b"\xc0") == (b"ab",)  # the bare END ends the frame
    assert decoder.feed(b"cd\xc0") == (b"cd",)
    assert decoder.counters == SlipCounters(framing=0, overrun=0)


def test_unframed_noise_is_discarded_and_counted_once_per_run() -> None:
    """Garbage with no frame boundary behind it is a half frame whose start was lost:
    discarded, never emitted, one `framing` per contiguous run (slip.py's module
    docstring). Karn's flush, RFC 1055, PROTOCOL: "If there was line noise, the data
    received due to it will be discarded without affecting the following packet." """
    decoder = SlipDecoder()
    assert decoder.feed(b"\xde\xad\xbe\xef") == ()  # the run is counted as it opens
    assert decoder.counters == SlipCounters(framing=1, overrun=0)
    assert decoder.feed(b"more") == ()  # the same run: still exactly one
    assert decoder.counters == SlipCounters(framing=1, overrun=0)
    assert decoder.feed(b"\xc0ok\xc0") == (b"ok",)  # the following packet is untouched
    assert decoder.counters == SlipCounters(framing=1, overrun=0)


def test_end_delimited_garbage_is_a_frame_the_codec_never_guesses() -> None:
    """The pinned no-guess rule: garbage delimited by two ENDs is byte-identical to a
    data frame and is delivered as one — SLIP carries no checksum ("error detection is
    not absolutely necessary at the SLIP level because any IP application should
    detect damaged packets", RFC 1055, DEFICIENCIES), so dropping it is the IP
    layer's job. The codec never second-guesses the wire."""
    decoder = SlipDecoder()
    assert decoder.feed(b"\xc0a\xc0garbage\xc0b\xc0") == (b"a", b"garbage", b"b")
    assert decoder.counters == SlipCounters(framing=0, overrun=0)


def test_an_over_mtu_frame_is_dropped_whole_and_counted_overrun() -> None:
    """An RX frame over the MTU is dropped whole and counted `overrun` — the
    reference `recv_packet` truncates silently ("If more than len bytes are received,
    the packet will be truncated"); truncation is a wrong parse half-applied (§12)
    and refused here. The next frame is untouched."""
    decoder = SlipDecoder(mtu=4)
    assert decoder.feed(b"\xc0abcde\xc0") == ()
    assert decoder.counters == SlipCounters(framing=0, overrun=1)
    assert decoder.feed(b"\xc0abcd\xc0") == (b"abcd",)  # exactly mtu is fine
    assert decoder.counters == SlipCounters(framing=0, overrun=1)


def test_one_dropped_frame_counts_exactly_one_error() -> None:
    """A frame faulted twice is counted once — the first fault decides the counter
    (slip.py's module docstring): overrun poisoned this frame before its truncated
    escape arrived."""
    decoder = SlipDecoder(mtu=2)
    assert decoder.feed(b"\xc0abc\xdb") == ()  # the overrun poisons first
    assert decoder.feed(b"\xc0") == ()  # the truncated escape: not counted again
    assert decoder.counters == SlipCounters(framing=0, overrun=1)


