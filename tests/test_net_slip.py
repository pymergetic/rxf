def test_the_line_carries_a_packet_both_ways_over_the_wire() -> None:
    """The §13 device face end to end: write -> line bytes -> read on the other side,
    both directions. The line bytes on `sent` are byte-exact RFC 1055 — all four
    special bytes stuffed exactly where the RFC says."""
    pair = SlipLinePair()
    pair.near.open()
    pair.far.open()
    pair.near.set_knob("net/dev/slip0", Knob.LINK, LinkState.UP)
    pair.far.set_knob("net/dev/slip1", Knob.LINK, LinkState.UP)
    payload = bytes((END, ESC, ESC_END, ESC_ESC))
    assert pair.near.write(payload) == 4
    assert bytes(pair.near.sent) == b"\xc0\xdb\xdc\xdb\xdd\xdc\xdd\xc0"
    assert pair.far.read() == payload
    assert pair.far.write(b"pong") == 4
    assert bytes(pair.far.sent) == b"\xc0pong\xc0"
    assert pair.near.read() == b"pong"
    with pytest.raises(WouldBlock):
        pair.near.read()  # nothing complete is waiting


def test_the_wire_may_deliver_in_pieces() -> None:
    """The device face over a chunky wire (§13's uart/js seats deliver in pieces):
    whatever pieces arrive, the far end reads exactly the packet — and never a half
    packet before the line completes it."""
    far = SlipLine("net/dev/slip1")
    pieces: list[bytes] = []

    def wire(line: bytes) -> None:
        for index in range(0, len(line), 2):
            piece = line[index : index + 2]
            pieces.append(piece)
            far.feed(piece)

    near = SlipLine("net/dev/slip0", on_wire=wire)
    near.open()
    far.open()
    near.set_knob("net/dev/slip0", Knob.LINK, LinkState.UP)
    assert near.write(b"\xc0split\xc0") == 7
    assert b"".join(pieces) == bytes(near.sent)  # the wire carried the whole frame
    assert far.read() == b"\xc0split\xc0"
    with pytest.raises(WouldBlock):
        far.read()


def test_the_lifecycle_gates_every_face_by_name() -> None:
    """§13's `open/close` face and §7's vanish rule, pinned: the picture answers for a
    configured device before `open` (an ethtool read needs no open line), the data
    faces refuse `NotConnected` until `open`, `open` on an open line refuses
    `NotSupported`, and after `close` every face refuses `StaleHandle` — a closed line
    is a gone device, one-way like the stream fills."""
    line = SlipLine()
    assert line.hardware("net/dev/slip0").link is LinkState.DOWN  # config before open
    for operation in (
        lambda: line.write(b"x"),
        lambda: line.read(),
        lambda: line.feed(b"\xc0"),
        lambda: line.wait(Interest.READ),
    ):
        with pytest.raises(NotConnected):
            operation()
    line.open()
    with pytest.raises(NotSupported):
        line.open()
    line.close()
    line.close()  # a close is idempotent, like the stream fills'
    for operation in (
        lambda: line.write(b"x"),
        lambda: line.read(),
        lambda: line.feed(b"\xc0"),
        lambda: line.wait(Interest.READ),
        lambda: line.hardware("net/dev/slip0"),
        lambda: line.set_knob("net/dev/slip0", Knob.MTU, 500),
        lambda: line.counters,
    ):
        with pytest.raises(StaleHandle):
            operation()
    with pytest.raises(StaleHandle):
        line.open()  # a closed line is gone for good (§7)


def test_a_down_line_refuses_tx_and_carries_no_write_readiness() -> None:
    """Creation is config, bring-up is its own write (§7): a down line refuses TX
    `LinkDown` (§15) and reports no WRITE readiness — while the wire keeps its side
    of the bargain and RX admits what it delivered."""
    pair = SlipLinePair()
    pair.near.open()
    pair.far.open()
    with pytest.raises(LinkDown):
        pair.near.write(b"x")
    assert pair.near.wait(Interest.READ | Interest.WRITE) == Interest(0)
    pair.near.set_knob("net/dev/slip0", Knob.LINK, LinkState.UP)
    assert pair.near.wait(Interest.WRITE) == Interest.WRITE
    assert pair.near.write(b"x") == 1
    assert pair.far.read() == b"x"  # the far end is still down; the wire still landed


def test_the_mtu_default_and_the_knob_retune_both_directions() -> None:
    """§13: MTU 1000 default, settable — the RFC's 1006 is the named note (slip.py's
    module docstring). The knob bounds TX (`MessageTooLong`, §15) and retunes the
    decoder's RX limit (`overrun`) — one word, both directions."""
    line = SlipLine()
    line.open()
    line.set_knob("net/dev/slip0", Knob.LINK, LinkState.UP)
    assert line.hardware("net/dev/slip0").mtu == DEFAULT_MTU == 1000
    assert line.write(b"x" * DEFAULT_MTU) == DEFAULT_MTU
    with pytest.raises(MessageTooLong):
        line.write(b"x" * (DEFAULT_MTU + 1))
    line.set_knob("net/dev/slip0", Knob.MTU, 1006)  # RFC 1055's peer, set by name
    assert line.hardware("net/dev/slip0").mtu == 1006
    assert line.write(b"x" * 1006) == 1006
    line.feed(b"\xc0" + b"y" * 1007 + b"\xc0")
    assert line.counters == SlipCounters(framing=0, overrun=1)  # the knob retuned RX


def test_the_line_is_point_to_point_with_no_mac() -> None:
    """§3: point-to-point devices have `mac: None` — the picture says so and the MAC
    knob refuses `NotSupported` by name (§7: a knob this device cannot do is never a
    silent no-op that reports success)."""
    line = SlipLine()
    picture = line.hardware("net/dev/slip0")
    assert picture.mac is None
    assert picture.speed is None and picture.duplex is None
    assert picture.offloads == frozenset() and picture.rings is None
    with pytest.raises(NotSupported):
        line.set_knob("net/dev/slip0", Knob.MAC, b"\x02" * 6)
    with pytest.raises(NotSupported):
        line.set_knob("net/dev/slip0", Knob.RINGS, (256, 256))


def test_the_error_counters_are_image_words_on_the_line() -> None:
    """§13's counters (`framing`, `overrun`) as image words on the line face: a
    malformed frame and an over-MTU frame each land in their counter, and complete
    packets are unaffected."""
    line = SlipLine()
    line.open()
    line.feed(b"\xc0ab\xdb\xc0")  # a malformed frame
    line.feed(b"\xc0" + b"x" * (DEFAULT_MTU + 1) + b"\xc0")  # an overrun frame
    line.feed(b"\xc0ok\xc0")
    assert line.counters == SlipCounters(framing=1, overrun=1)
    assert line.read() == b"ok"


def test_readiness_is_the_wait_notify_face() -> None:
    """§13's byte-source readiness, into the run's wait/notify — level-triggered only
    (§4): READ while a complete packet waits (a half frame never makes the source
    ready), WRITE while the line is open and up, and an empty wake otherwise (§4: a
    timeout is never an error)."""
    line = SlipLine()
    line.open()
    line.set_knob("net/dev/slip0", Knob.LINK, LinkState.UP)
    assert line.wait(Interest.READ) == Interest(0)  # nothing ready: an empty wake
    line.feed(b"\xc0ab")  # half a frame
    assert line.wait(Interest.READ) == Interest(0)  # never ready on a half frame
    line.feed(b"\xc0")
    assert line.wait(Interest.READ | Interest.WRITE) == Interest.READ | Interest.WRITE
    assert line.read() == b"ab"
    assert line.wait(Interest.READ) == Interest(0)


def test_the_fill_records_its_knob_sets() -> None:
    """The on-demand pin, the same shape `MemoryDriver.applied` keeps: every knob set
    through this line is on the log — and a refused one lands nothing."""
    line = SlipLine()
    line.set_knob("net/dev/slip0", Knob.LINK, LinkState.UP)
    with pytest.raises(NotSupported):
        line.set_knob("net/dev/slip0", Knob.MAC, b"\x02" * 6)
    line.set_knob("net/dev/slip0", Knob.MTU, 500)
    assert line.applied == [
        ("net/dev/slip0", Knob.LINK, LinkState.UP),
        ("net/dev/slip0", Knob.MTU, 500),
    ]  # the refusals applied nothing


def test_the_line_is_a_fill_of_the_device_seam() -> None:
    """`cap.net.driver` (§7) — the line installs through the same seam any other link
    device's fill does: the picture at its path answers (§3: `mac: None`), a foreign
    path is a gone device (`StaleHandle`), and removing the provider restores the
    seam's own refusal."""
    line = SlipLine()
    install_driver(line)
    try:
        assert hardware("net/dev/slip0").mac is None
        with pytest.raises(StaleHandle):
            hardware("net/dev/eth0")
    finally:
        install_driver(None)
    with pytest.raises(NotSupported):
        hardware("net/dev/slip0")  # no provider: the seam refuses by name (§7)


