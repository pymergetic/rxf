def test_cslip_stays_a_refused_card_by_name() -> None:
    """§13: VJ header compression stays a refused card, not a silent default — and
    refused BY NAME. There is no second framing to guard at runtime (module
    docstring: no "SLIP-with-extensions"), so the name lives where the refusal is
    written and this pin keeps it there."""
    docstring = slip_module.__doc__ or ""
    assert "CSLIP" in docstring
    assert "refused cards" in docstring
