"""The build step of the highlighting: ``meaning.json`` -> the TextMate grammars.

The meaning table is the one source; this derives the alternations of the
grammars from it and writes them to ``editors/rxf-highlight/syntaxes``. The
grammars are generated bytes: rerunning this must reproduce the checked-in files
byte for byte (``tests/test_highlight.py`` compares them), so never edit a
grammar by hand — edit the table and run this.

    python3 -m tools.highlight.grammar_gen           # write the grammars
    python3 -m tools.highlight.grammar_gen --check   # fail when they are stale

(run from ``packages/rxf``, where ``tools`` is importable)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from .meaning import Table
from .meaning import load as load_table

HERE = Path(__file__).resolve().parent
PACKAGE = HERE.parents[1]  # packages/rxf
SYNTAXES = PACKAGE / "editors" / "rxf-highlight" / "syntaxes"
RXFS_GRAMMAR = "rxfs.tmLanguage.json"
RXFD_GRAMMAR = "rxfd.tmLanguage.json"

SCHEMA = "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json"


def alternation(words: list[str] | tuple[str, ...]) -> str:
    """The words as one regex alternation, the longest first (so `ret` never
    stands in the way of `return`). A word that appears twice is written once."""
    return "|".join(
        re.escape(word) for word in sorted(set(words), key=lambda w: (-len(w), w))
    )


def render_rxfs(table: Table) -> dict[str, object]:
    """The grammar of ``.rxfs``: the program language of ``tools/native/rxfc.py``.

    What is derived from the table: the keywords and their scopes, the builtin
    calls, and the operators colored by the class of the leaf they lower to (see
    the `lowering` of every operator in the table — where the mapping is not 1:1
    the scope says `desugared`)."""
    rxfs = table.rxfs
    function_words = [w for g in rxfs.keywords if g.group == "function" for w in g.words]
    call_words = [w for g in rxfs.keywords if g.group == "proc" for w in g.words if w == "call"]
    builtin_names = [builtin.name for builtin in rxfs.builtins]
    scopes: list[str] = []
    for operator in rxfs.operators:
        if operator.scope not in scopes:
            scopes.append(operator.scope)
    operator_patterns: list[dict[str, object]] = [
        {
            "name": scope,
            "match": alternation([o.token for o in rxfs.operators if o.scope == scope]),
        }
        for scope in scopes
    ]
    keywords: list[dict[str, object]] = [
        {"name": group.scope, "match": f"\\b({alternation(group.words)})\\b"}
        for group in rxfs.keywords
    ]
    return {
        "$schema": SCHEMA,
        "name": "RXF Source",
        "scopeName": rxfs.scope_name,
        "patterns": [
            {"include": "#comment"},
            {"include": "#declaration"},
            {"include": "#call"},
            {"include": "#string"},
            {"include": "#keyword"},
            {"include": "#builtin"},
            {"include": "#number"},
            {"include": "#constant"},
            {"include": "#operator"},
            {"include": "#punctuation"},
        ],
        "repository": {
            "comment": {"name": "comment.line.number-sign.rxfs", "match": "#.*$"},
            "declaration": {
                "match": f"\\b({alternation(function_words)})\\s+([A-Za-z_][A-Za-z0-9_]*)",
                "captures": {
                    "1": {"name": "storage.type.function.rxfs"},
                    "2": {"name": "entity.name.function.rxfs"},
                },
            },
            "call": {
                "match": f"\\b({alternation(call_words)})\\s+([A-Za-z_][A-Za-z0-9_]*)",
                "captures": {
                    "1": {"name": "keyword.control.proc.rxfs"},
                    "2": {"name": "entity.name.function.rxfs"},
                },
            },
            "keyword": {"patterns": keywords},
            "builtin": {
                "name": "support.function.memory.rxfs",
                "match": f"\\b({alternation(builtin_names)})\\b(?=\\s*\\()",
            },
            "string": {
                "name": "string.quoted.double.rxfs",
                "begin": '"',
                "end": '"',
                "patterns": [{"name": "constant.character.escape.rxfs", "match": "\\\\."}],
            },
            "number": {
                "patterns": [
                    {"name": "constant.numeric.hex.rxfs", "match": "\\b0[xX][0-9a-fA-F_]+\\b"},
                    {"name": "constant.numeric.decimal.rxfs", "match": "\\b[0-9][0-9_]*\\b"},
                ]
            },
            "constant": {
                "name": "constant.other.rxfs",
                "match": "\\b[A-Z][A-Z0-9_]{2,}\\b",
            },
            "operator": {"patterns": operator_patterns},
            "punctuation": {"name": "punctuation.separator.rxfs", "match": "[(){},;:]"},
        },
    }


def render_rxfd(table: Table) -> dict[str, object]:
    """The grammar of ``.rxfd``: the delta documents of ``core/xml/xml.hpp``.

    What is derived from the table: the elements and attributes of the pinned
    corpora, the `rxf` namespace, the enum vocabulary (a value like
    ``pymergetic.rxf.kinds.FunctionImplementation.Semantic`` names an Enumerator
    object) and the three reference shapes (``signature=``, ``refusal_set=``,
    ``rxf:parent=``), which get a scope of their own so the stage-3 webview and
    a validator can tell a reference from a name."""
    rxfd = table.rxfd
    namespace = rxfd.namespace
    reference_attributes = [shape.attribute for shape in rxfd.references]
    namespace_attributes = list(namespace.attributes)
    enum_types = sorted({entry.type for entry in rxfd.enums})
    element_words = list(rxfd.elements)
    plain_attributes = list(rxfd.attributes)
    return {
        "$schema": SCHEMA,
        "name": "RXF Delta",
        "scopeName": rxfd.scope_name,
        "patterns": [
            {"include": "#comment"},
            {"include": "#prolog"},
            {"include": "#rxf-tag"},
            {"include": "#tag"},
            {"include": "#any-tag"},
        ],
        "repository": {
            "comment": {"name": "comment.block.xml.rxfd", "begin": "<!--", "end": "-->"},
            "prolog": {
                "name": "meta.tag.prolog.rxfd",
                "begin": "<\\?",
                "end": "\\?>",
                "patterns": [{"include": "#any-attribute"}],
            },
            "rxf-tag": {
                "name": "meta.tag.namespace.rxfd",
                "begin": f"(<)(/?)(?:({namespace.prefix})(:))?({alternation(namespace.elements)})\\b",
                "beginCaptures": {
                    "1": {"name": "punctuation.definition.tag.begin.rxfd"},
                    "2": {"name": "punctuation.definition.tag.end.rxfd"},
                    "3": {"name": "entity.name.namespace.rxfd"},
                    "4": {"name": "punctuation.separator.namespace.rxfd"},
                    "5": {"name": "entity.name.tag.namespace.rxfd"},
                },
                "end": "(/?>)",
                "endCaptures": {"1": {"name": "punctuation.definition.tag.end.rxfd"}},
                "patterns": [{"include": "#attributes"}],
            },
            "tag": {
                "name": "meta.tag.rxfd",
                "begin": f"(<)(/?)(?:({namespace.prefix})(:))?({alternation(element_words)})\\b",
                "beginCaptures": {
                    "1": {"name": "punctuation.definition.tag.begin.rxfd"},
                    "2": {"name": "punctuation.definition.tag.end.rxfd"},
                    "3": {"name": "entity.name.namespace.rxfd"},
                    "4": {"name": "punctuation.separator.namespace.rxfd"},
                    "5": {"name": "entity.name.tag.rxfd"},
                },
                "end": "(/?>)",
                "endCaptures": {"1": {"name": "punctuation.definition.tag.end.rxfd"}},
                "patterns": [{"include": "#attributes"}],
            },
            "any-tag": {
                "name": "meta.tag.rxfd",
                "begin": "(<)(/?)([A-Za-z_][\\w:.-]*)",
                "beginCaptures": {
                    "1": {"name": "punctuation.definition.tag.begin.rxfd"},
                    "2": {"name": "punctuation.definition.tag.end.rxfd"},
                    "3": {"name": "entity.name.tag.rxfd"},
                },
                "end": "(/?>)",
                "endCaptures": {"1": {"name": "punctuation.definition.tag.end.rxfd"}},
                "patterns": [{"include": "#attributes"}],
            },
            "attributes": {
                "patterns": [
                    {"include": "#xmlns-attribute"},
                    {"include": "#reference-attribute"},
                    {"include": "#data-attribute"},
                    {"include": "#namespace-attribute"},
                    {"include": "#enum-attribute"},
                    {"include": "#any-attribute"},
                ]
            },
            "xmlns-attribute": {
                "begin": f"(xmlns)(:)({namespace.prefix})(=)(\")",
                "beginCaptures": {
                    "1": {"name": "entity.other.attribute-name.namespace.rxfd"},
                    "2": {"name": "punctuation.separator.namespace.rxfd"},
                    "3": {"name": "entity.name.namespace.rxfd"},
                    "4": {"name": "punctuation.separator.key-value.rxfd"},
                    "5": {"name": "punctuation.definition.string.begin.rxfd"},
                },
                "end": "\"",
                "endCaptures": {"0": {"name": "punctuation.definition.string.end.rxfd"}},
                "name": "string.quoted.double.rxfd",
                "patterns": [
                    {"match": re.escape(namespace.urn), "name": "constant.other.urn.rxfd"}
                ],
            },
            "reference-attribute": {
                "begin": f"({alternation(reference_attributes)})(=)(\")",
                "beginCaptures": {
                    "1": {"name": "entity.other.attribute-name.reference.rxfd"},
                    "2": {"name": "punctuation.separator.key-value.rxfd"},
                    "3": {"name": "punctuation.definition.string.begin.rxfd"},
                },
                "end": "\"",
                "endCaptures": {"0": {"name": "punctuation.definition.string.end.rxfd"}},
                "name": "meta.attribute.value.reference.rxfd",
                "patterns": [{"include": "#reference-value"}],
            },
            "data-attribute": {
                "begin": f"((?:{namespace.prefix})(:))?(data)(=)(\")",
                "beginCaptures": {
                    "1": {"name": "entity.other.attribute-name.namespace.rxfd"},
                    "3": {"name": "entity.other.attribute-name.namespace.rxfd"},
                    "4": {"name": "punctuation.separator.key-value.rxfd"},
                    "5": {"name": "punctuation.definition.string.begin.rxfd"},
                },
                "end": "\"",
                "endCaptures": {"0": {"name": "punctuation.definition.string.end.rxfd"}},
                "name": "string.quoted.double.rxfd",
                "patterns": [{"match": "[0-9a-fA-F]+", "name": "constant.numeric.hex.rxfd"}],
            },
            "namespace-attribute": {
                "begin": f"(({namespace.prefix})(:))?({alternation(namespace_attributes)})(=)(\")",
                "beginCaptures": {
                    "1": {"name": "entity.other.attribute-name.namespace.rxfd"},
                    "2": {"name": "entity.name.namespace.rxfd"},
                    "4": {"name": "entity.other.attribute-name.namespace.rxfd"},
                    "5": {"name": "punctuation.separator.key-value.rxfd"},
                    "6": {"name": "punctuation.definition.string.begin.rxfd"},
                },
                "end": "\"",
                "endCaptures": {"0": {"name": "punctuation.definition.string.end.rxfd"}},
                "name": "string.quoted.double.rxfd",
                "patterns": [{"include": "#value"}],
            },
            "enum-attribute": {
                "begin": f"({alternation(plain_attributes)})(=)(\")",
                "beginCaptures": {
                    "1": {"name": "entity.other.attribute-name.rxfd"},
                    "2": {"name": "punctuation.separator.key-value.rxfd"},
                    "3": {"name": "punctuation.definition.string.begin.rxfd"},
                },
                "end": "\"",
                "endCaptures": {"0": {"name": "punctuation.definition.string.end.rxfd"}},
                "name": "string.quoted.double.rxfd",
                "patterns": [{"include": "#value"}],
            },
            "any-attribute": {
                "match": "([A-Za-z_:][\\w:.-]*)(=)(\"[^\"]*\")",
                "captures": {
                    "1": {"name": "entity.other.attribute-name.rxfd"},
                    "2": {"name": "punctuation.separator.key-value.rxfd"},
                    "3": {"name": "string.quoted.double.rxfd"},
                },
            },
            "value": {
                "patterns": [
                    {"include": "#alias-marker"},
                    {"include": "#enum-value"},
                    {"include": "#number-value"},
                ]
            },
            "reference-value": {
                "patterns": [
                    {"include": "#alias-marker"},
                    {
                        "match": "\\.",
                        "name": "punctuation.separator.path.rxfd",
                    },
                    {
                        "match": "[A-Za-z_][A-Za-z0-9_]*(?:\\[\\d+\\])?",
                        "name": "entity.name.reference.rxfd",
                    },
                ]
            },
            "alias-marker": {"match": "@", "name": "punctuation.definition.alias.rxfd"},
            "enum-value": {
                "match": (
                    f"(?:[A-Za-z_][A-Za-z0-9_]*\\.)*({alternation(enum_types)})"
                    f"\\.([A-Z][A-Za-z0-9_]*(?:\\|[A-Z][A-Za-z0-9_]*)*)"
                ),
                "captures": {
                    "1": {"name": "support.type.enum.rxfd"},
                    "2": {"name": "constant.language.enumerator.rxfd"},
                },
            },
            "number-value": {"match": "\\b[0-9]+\\b", "name": "constant.numeric.rxfd"},
        },
    }


def render_all(table: Table | None = None) -> dict[str, str]:
    """The generated bytes of every grammar, by file name."""
    table = table or load_table()
    return {
        RXFS_GRAMMAR: json.dumps(render_rxfs(table), indent=2, ensure_ascii=False) + "\n",
        RXFD_GRAMMAR: json.dumps(render_rxfd(table), indent=2, ensure_ascii=False) + "\n",
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name, text in sorted(render_all().items()):
        path = SYNTAXES / name
        current = path.read_text() if path.exists() else None
        if current == text:
            print(f"up to date: {path.relative_to(PACKAGE)}")
            continue
        stale.append(path)
        if check:
            print(f"STALE: {path.relative_to(PACKAGE)} (run python3 tools/highlight/grammar_gen.py)")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote: {path.relative_to(PACKAGE)}")
    return 1 if check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
