"""The SLIP line, complete (docs/25 §13): RFC 1055 framing as a streaming codec and
the device face that carries it.

SLIP is "merely a packet framing protocol: SLIP defines a sequence of characters that
frame IP packets on a serial line, and nothing more" (RFC 1055, HISTORY). The protocol
source of record is RFC 1055 (Romkey, June 1988), "A Nonstandard for Transmission of
IP Datagrams Over Serial Lines: SLIP" — its PROTOCOL and SLIP DRIVERS sections — and
this module is that framing plus the §13 line contract over it: `open/close`, byte
write (TX), byte-source readiness (RX, into the run's wait/notify), MTU (1000 default,
settable), and the error counters (`framing`, `overrun`) as image words.

Framing (RFC 1055, PROTOCOL): END and ESC are the only special characters; a data
byte equal to END is sent as ESC ESC_END, one equal to ESC as ESC ESC_ESC, and a
packet ends with an END. The encoder follows Phil Karn's change, which the reference
`send_packet` implements: packets begin as well as end with END — "This will flush any
erroneous bytes which have been caused by line noise" (RFC 1055, PROTOCOL).

Policies RFC 1055 leaves open, decided here by name and pinned in
`tests/test_net_slip.py` — never silently picked:

- **Empty frames are skipped.** A bare END ends the frame in progress (and syncs the
  line); the empty frames between ENDs are never emitted — the reference
  `recv_packet`'s own "minor optimization" (RFC 1055, SLIP DRIVERS): "if there is no
  data in the packet, ignore it ... to avoid bothering IP with all the empty packets
  generated by the duplicate END characters". Not an error: no counter moves.
- **An escape truncated by the frame's end is a malformed frame: drop, count, resync.**
  ESC as a frame's final byte (ESC END) drops the whole frame — never half of one —
  counts one `framing`, and the END stays the frame boundary for what follows. This
  deviates from the reference `recv_packet`, whose best-bet path would stuff the END
  byte literally and swallow the frame boundary with it; a guessed byte is "a wrong
  parse half-applied" (docs/25 §12) and is refused here.
- **ESC + a byte that is neither ESC_END nor ESC_ESC keeps the reference's best bet:
  the byte is stuffed into the packet literally** (RFC 1055, SLIP DRIVERS: "if 'c' is
  not one of these two, then we have a protocol violation. The best bet seems to be to
  leave the byte alone and just stuff it into the packet") — kept and pinned
  byte-exact, quirks included.
- **The decoder never emits a half frame.** Bytes with no frame boundary behind them
  (the line started mid-frame; the frame's start was lost to noise) are line noise:
  discarded, never emitted, one `framing` per contiguous run. A frame is emitted only
  when its closing END has been seen — complete, or not at all.
- **Garbage delimited by two ENDs is a frame.** SLIP carries no checksum ("error
  detection is not absolutely necessary at the SLIP level because any IP application
  should detect damaged packets", RFC 1055, DEFICIENCIES): an END-delimited run is
  byte-identical to a data frame and is delivered as one — dropping it is the IP
  layer's job. The codec never guesses.
- **An over-MTU frame on RX is dropped whole and counted `overrun`** — never silently
  truncated the way the reference `recv_packet` truncates ("If more than len bytes are
  received, the packet will be truncated"): truncation is a wrong parse half-applied
  (§12). On TX an over-MTU packet is refused `MessageTooLong` (§15) — never sent short.
- **An empty payload is refused `NotSupported`** at the codec and at the line: the
  reference `send_packet` would put `END END` on the wire, which every receiver — its
  own `recv_packet` included — throws away. Bytes the protocol guarantees to discard
  are a silent no-op; this face refuses by name instead.
- **One dropped frame counts exactly one error**: the first fault that poisoned the
  frame decides whether it lands in `framing` or `overrun`.

Refused by name (§13): Van Jacobson TCP header compression (CSLIP, RFC 1144) and any
other "SLIP-with-extensions" framing stay refused cards, not silent defaults — there
is no second framing in this module and none may be added; this is RFC 1055's framing
and nothing more. Named note (§13 vs RFC 1055, PROTOCOL): the RFC says a new
implementation "should be prepared to accept 1006 byte datagrams" (the Berkeley
driver's maximum); §13 pins the line's default MTU at 1000 — the `mtu` knob sets any
positive word, so a seat interoperating with a 1006-byte peer sets it.

The device face is one `cap.net.driver` fill in the shape of `net.link.device`
(§2, §7): the interface is the truth, this is the honest in-memory fill — the same way
`MemoryDriver` fills the device seam and `MemoryPair` fills the stream seam. §13's
per-seat fills (`slip_line_host.c`, `slip_line_tap.c`, `slip_line_js.c`,
`slip_line_uart.c`) run the same contract suite on every seat; this module is the
contract and its one in-memory seat, never a second stack inside a fill. The guest
side deframes into `netif->input` (docs/23 §4.4) — `SlipDecoder`'s output is exactly
the packets that callback takes, complete or absent.
"""

from __future__ import annotations

from collections import deque
from collections.abc import Callable
from dataclasses import dataclass

from ..schema import (
    Hardware,
    Interest,
    LinkDown,
    LinkState,
    MessageTooLong,
    NotConnected,
    NotSupported,
    StaleHandle,
    WouldBlock,
)
from .device import DeviceDriver, Knob, MemoryDriver

# RFC 1055, SLIP DRIVERS — the reference `#define`s, byte-exact:
# END is octal 300 (decimal 192), ESC is octal 333 (219) "not to be confused with the
# ASCII ESCape character", ESC_END is octal 334 (220) ("ESC ESC_END means END data
# byte"), ESC_ESC is octal 335 (221) ("ESC ESC_ESC means ESC data byte").
END = 0o300
ESC = 0o333
ESC_END = 0o334
ESC_ESC = 0o335

DEFAULT_MTU = 1000  # docs/25 §13; RFC 1055, PROTOCOL says 1006 (module docstring)

_END = bytes((END,))
# RFC 1055, PROTOCOL: only END and ESC are stuffed — ESC_END and ESC_ESC as payload
# bytes are ordinary data on the wire.
_STUFFING = {END: bytes((ESC, ESC_END)), ESC: bytes((ESC, ESC_ESC))}


def _bytes(value: object, what: str) -> bytes:
    """Bytes or a refusal by name — a wrong shape is never a silent wrong parse."""
    if not isinstance(value, bytes):
        raise NotSupported(f"{what} is bytes: this value is not one")
    return value


@dataclass(frozen=True)
class SlipCounters:
    """The §13 error counters as image words.

    `framing` counts every framing fault this codec drops: a malformed frame (an
    escape truncated by the frame's end) and one per contiguous unframed-noise run.
    `overrun` counts the frames dropped whole for exceeding the MTU — the line never
    truncates one (§12: a wrong parse half-applied is refused).
    """

    framing: int
    overrun: int


class SlipEncoder:
    """The streaming RFC 1055 encoder — one codec, whatever chunks arrive.

    `feed` takes a chunk of one packet and answers its stuffed line bytes (the frame's
    initial END — Karn's flush — rides out with the first non-empty chunk); `finish`
    closes the frame with its trailing END and the encoder starts the next one. The
    whole-packet face `encode` is this encoder in one call. An empty frame is refused
    `NotSupported` at `finish` (module docstring: the encoder never writes what every
    receiver must discard).
    """

    def __init__(self) -> None:
        self._started = False

    def feed(self, payload: bytes) -> bytes:
        """Stuff this chunk of the packet into line bytes (RFC 1055, PROTOCOL: END is
        sent as ESC ESC_END, ESC as ESC ESC_ESC; everything else rides bare)."""
        chunk = _bytes(payload, "a packet")
        out = bytearray()
        if chunk and not self._started:
            self._started = True
            out += _END  # "send an initial END character to flush out any ... line noise"
        for byte in chunk:
            out += _STUFFING.get(byte, bytes((byte,)))
        return bytes(out)

    def finish(self) -> bytes:
        """Close the frame: "When the last byte in the packet has been sent, an END
        character is then transmitted" (RFC 1055, PROTOCOL). A frame with nothing fed
        is an empty frame and is refused `NotSupported` — never written for the
        receiver to throw away."""
        if not self._started:
            raise NotSupported("an empty frame is refused: a SLIP frame carries one packet (module docstring)")
        self._started = False
        return _END


def encode(payload: bytes) -> bytes:
    """One packet onto the line as one RFC 1055 frame — the reference `send_packet`
    of RFC 1055, SLIP DRIVERS, byte-exact: the initial END (Karn's flush), the
    stuffing, the trailing END. An empty payload is refused `NotSupported`."""
    encoder = SlipEncoder()
    return encoder.feed(payload) + encoder.finish()


class SlipDecoder:
    """The streaming RFC 1055 decoder — `feed` takes whatever chunks the wire
    delivers (split buffers are the normal case) and answers only whole packets.

    The decoder never emits a half frame: a packet appears at its closing END, whole,
    or not at all. The open policies — the empty-frame skip, the malformed-frame drop
    for an escape truncated by the frame's end, the best-bet literal stuffing, the
    noise discard, the overrun drop — are named and pinned in the module docstring.
    `mtu` is the live MTU (§13's settable word); the line keeps it in step with the
    `mtu` knob.
    """

    def __init__(self, *, mtu: int = DEFAULT_MTU) -> None:
        if not isinstance(mtu, int) or isinstance(mtu, bool) or mtu <= 0:
            raise NotSupported("the mtu is a positive word: this value is not one")
        self.mtu = mtu
        self._frame = bytearray()
        self._escape = False
        self._fault: str | None = None  # the first fault to poison the open frame
        self._seeking = True  # no boundary seen yet: everything is a half frame
        self._noise = False  # a noise run is open (counted once when it opens)
        self._framing = 0
        self._overrun = 0

    def feed(self, data: bytes) -> tuple[bytes, ...]:
        """Line bytes in, whole packets out — the ones this chunk completed, in order."""
        chunk = _bytes(data, "line bytes")
        frames: list[bytes] = []
        for byte in chunk:
            if self._seeking:
                # Bytes with no boundary behind them are a half frame whose start was
                # lost — noise, never emitted (module docstring; Karn's flush).
                if byte == END:
                    self._seeking = False
                    self._noise = False
                    self._frame.clear()
                    self._escape = False
                    self._fault = None
                elif not self._noise:
                    self._noise = True
                    self._framing += 1
                continue
            if self._escape:
                self._escape = False
                if byte == ESC_END:
                    self._append(END)
                elif byte == ESC_ESC:
                    self._append(ESC)
                elif byte == END:
                    # ESC as the frame's final byte: a malformed frame — dropped
                    # whole, counted once (module docstring; the reference code's
                    # guessed literal byte is refused).
                    self._fault = self._fault or "framing"
                    frames.extend(self._close())
                else:
                    self._append(byte)  # the RFC's best bet: stuff the byte alone
                continue
            if byte == END:
                frames.extend(self._close())
            elif byte == ESC:
                self._escape = True
            else:
                self._append(byte)
        return tuple(frames)

    @property
    def counters(self) -> SlipCounters:
        """The §13 error counters as image words."""
        return SlipCounters(framing=self._framing, overrun=self._overrun)

    def _append(self, byte: int) -> None:
        if self._fault is not None:
            return  # a poisoned frame stores nothing more (its memory stays bounded)
        self._frame.append(byte)
        if len(self._frame) > self.mtu:
            self._fault = "overrun"  # dropped whole at the boundary, never truncated
            self._frame.clear()

    def _close(self) -> tuple[bytes, ...]:
        """The open frame at its boundary: emitted whole, or dropped with its one
        error count. An empty frame is skipped (RFC 1055's recv_packet quirk)."""
        outcome: tuple[bytes, ...] = ()
        if self._fault == "framing":
            self._framing += 1
        elif self._fault == "overrun":
            self._overrun += 1
        elif self._frame:
            outcome = (bytes(self._frame),)
        self._frame.clear()
        self._escape = False
        self._fault = None
        return outcome


class SlipLine(DeviceDriver):
    """One SLIP line over a byte wire — the §13 `cap.net.driver` fill for a SLIP
    device, in the shape of the other link devices' fills (`net.link.device`).

    The faces, one line each:

    - `open`/`close` — the line's lifecycle (§13). Before `open` the data faces refuse
      `NotConnected`; after `close` every face refuses `StaleHandle` (§7: a device
      that is gone answers nothing) and the fill closes one way, like the stream
      fills — a seat that can reopen its serial port fills its own line.
    - `write` — TX (§13): one packet in, one RFC 1055 frame on the wire. A down line
      refuses `LinkDown` (§15), an over-MTU packet `MessageTooLong` (§15), an empty
      one `NotSupported` (module docstring).
    - `feed`/`read` — RX: raw line bytes in, complete packets out — the decoder never
      emits a half frame. The wire is outside the device: a down line still admits
      what the wire delivered, and frames already received are real.
    - `wait` — byte-source readiness (§13's run wait/notify face), level-triggered
      only (§4): READ while a complete packet waits, WRITE while the line is open and
      up; nothing ready is an empty wake.
    - `hardware`/`set_knob` — the `cap.net.driver` seam (§7): the honest picture (§3:
      point-to-point, `mac: None`, no speed or duplex word, no offloads, single-queue
      `rings: None`) and the honest knob set — MTU settable (the decoder's limit
      follows), LINK up/down, and every knob this device does not have refused
      `NotSupported` by name, never a silent no-op.
    - `counters` — the §13 error counters (`framing`, `overrun`) as image words.

    `sent` keeps the raw line bytes this end put on the wire and `applied` the knob
    sets through this line (the on-demand pin, `MemoryDriver.applied`'s shape) — both
    logs stay readable after close (a log is history).
    """

    def __init__(
        self,
        path: str = "net/dev/slip0",
        *,
        mtu: int = DEFAULT_MTU,
        on_wire: Callable[[bytes], None] | None = None,
    ) -> None:
        self._path = path
        self._decoder = SlipDecoder(mtu=mtu)  # validates the mtu word by construction
        self._frames: deque[bytes] = deque()
        self._opened = False
        self._closed = False
        self._on_wire = on_wire
        self.sent = bytearray()
        self._driver = MemoryDriver(
            {
                path: Hardware(
                    f"{path}/hw",
                    mtu,
                    None,  # point-to-point (§3): no MAC, ever
                    LinkState.DOWN,  # creation is config; bring-up is its own write
                    None,  # a byte line carries no speed word
                    None,  # and no duplex word
                    frozenset(),  # RFC 1055 stuffing is not an offload
                    None,  # single-queue: says so instead of pretending (§7)
                    None,  # no wake-on-lan on this device
                )
            }
        )

    # -- the §13 line faces --------------------------------------------------

    @property
    def path(self) -> str:
        """This line's device path."""
        return self._path

    def open(self) -> None:
        """Open the line (§13): TX and RX go from here. Open on an open line is
        refused `NotSupported`; a closed line is gone for good (`StaleHandle`, §7)."""
        if self._closed:
            raise StaleHandle(f"the line is gone: {self._path} was closed (§7)")
        if self._opened:
            raise NotSupported("open on an already-open line is refused by name")
        self._opened = True

    def close(self) -> None:
        """Close the line (§13): every face refuses from here (§7: the device is
        gone) — the one-way lifecycle of the stream fills. Idempotent, like theirs."""
        self._closed = True

    def write(self, payload: bytes) -> int:
        """TX one packet (§13): RFC 1055-framed onto the wire, all of it — a partial
        TX does not exist. Returns the payload bytes put on the line. The refusals, by
        name: `StaleHandle`/`NotConnected` on the wrong side of `open`/`close`,
        `LinkDown` on a down line (§15), `MessageTooLong` over the MTU (§15), and the
        codec's `NotSupported` for an empty payload."""
        self._guard_line()
        if self._driver.hardware(self._path).link is not LinkState.UP:
            raise LinkDown("the line is down: this device carries nothing until it is up (§7)")
        packet = _bytes(payload, "a packet")
        mtu = self._driver.hardware(self._path).mtu
        if len(packet) > mtu:
            raise MessageTooLong(f"the packet exceeds the mtu of {mtu} bytes (§15)")
        line = encode(packet)
        if self._on_wire is not None:
            self._on_wire(line)  # the wire first: a refused delivery refuses the write
        self.sent.extend(line)
        return len(packet)

    def feed(self, data: bytes) -> None:
        """RX: line bytes arrive from the wire (§13's byte source). Complete packets
        queue for `read`; the decoder never emits a half frame."""
        self._guard_line()
        for frame in self._decoder.feed(_bytes(data, "line bytes")):
            self._frames.append(frame)

    def read(self) -> bytes:
        """One complete packet from the line (§13 RX) — packets, not a byte stream:
        the guest side hands each one to `netif->input` (docs/23 §4.4). `WouldBlock`
        when no complete packet is waiting."""
        self._guard_line()
        if self._frames:
            return self._frames.popleft()
        raise WouldBlock("no complete packet is waiting")

    def wait(self, interest: Interest, timeout: int | None = None) -> Interest:
        """The §13 byte-source readiness face, into the run's wait/notify — level-
        triggered only (§4): READ while a complete packet waits (a half frame never
        makes the source ready), WRITE while the line is open and up. Nothing ready is
        an empty wake — a timeout is never an error (§4)."""
        self._guard_line()
        ready = Interest(0)
        if self._frames:
            ready |= Interest.READ
        if self._driver.hardware(self._path).link is LinkState.UP:
            ready |= Interest.WRITE
        return ready & interest

    # -- the cap.net.driver seam (§7) ----------------------------------------

    def hardware(self, path: str) -> Hardware:
        """The device's honest capability picture (§7), through this line's fill —
        present before `open` (an ethtool read needs no open line), gone after
        `close` (`StaleHandle`). A foreign path is a gone device too."""
        self._guard_device()
        return self._driver.hardware(path)

    def set_knob(self, path: str, knob: Knob, value: object) -> None:
        """One knob through this line's fill (§7): MTU settable (§13 — the decoder's
        limit follows), LINK up/down; the MAC knob refuses `NotSupported` — a
        point-to-point line has no address to set (§3) — and so does every knob this
        device does not have. Never a silent no-op that reports success."""
        self._guard_device()
        self._driver.set_knob(path, knob, value)
        self._decoder.mtu = self._driver.hardware(self._path).mtu

    @property
    def counters(self) -> SlipCounters:
        """The §13 error counters (`framing`, `overrun`) as image words, read back
        through the honest metrics face."""
        self._guard_device()
        return self._decoder.counters

    @property
    def applied(self) -> list[tuple[str, Knob, object]]:
        """The honest log of knob sets through this line — the on-demand pin, the
        same shape `MemoryDriver.applied` keeps."""
        return self._driver.applied

    # -- internals ------------------------------------------------------------

    def _guard_line(self) -> None:
        """The data faces need an open line (§13's lifecycle)."""
        if self._closed:
            raise StaleHandle(f"the line is gone: {self._path} was closed (§7)")
        if not self._opened:
            raise NotConnected("the line is not open")

    def _guard_device(self) -> None:
        """The device faces answer for a device that is present (§7) — configured
        before open, gone after close."""
        if self._closed:
            raise StaleHandle(f"the line is gone: {self._path} was closed (§7)")


class SlipLinePair:
    """One point-to-point SLIP line in memory: two ends and the byte wire between
    them — the honest in-memory fill of §13's per-seat `slip_line_*` contract, the way
    `MemoryPair` fills the stream seam.

    The wire is the pair itself: a `write` on one end lands on the other end's line
    (`sent` on each end keeps the raw line bytes for byte-exact pins). A delivery to
    a far end that is not open or gone refuses by name (`NotConnected`/`StaleHandle`)
    — never a silent drop into the void.
    """

    def __init__(
        self,
        near: str = "net/dev/slip0",
        far: str = "net/dev/slip1",
        *,
        mtu: int = DEFAULT_MTU,
    ) -> None:
        self.near = SlipLine(near, mtu=mtu, on_wire=self._to_far)
        self.far = SlipLine(far, mtu=mtu, on_wire=self._to_near)

    def _to_far(self, line: bytes) -> None:
        self._deliver(self.far, line)

    def _to_near(self, line: bytes) -> None:
        self._deliver(self.near, line)

    @staticmethod
    def _deliver(end: SlipLine, line: bytes) -> None:
        try:
            end.feed(line)
        except NotConnected as error:
            raise NotConnected(f"the far end is not open: {end.path}") from error
        except StaleHandle as error:
            raise StaleHandle(f"the far end is gone: {end.path}") from error
