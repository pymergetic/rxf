"""The network orchestration layer (docs/25): devices, sockets, filters, transports.

`pymergetic.rxf.net.schema` is the type set (§3): L2 devices and segments, the link and
hardware plane, L3 for both families, sockets with readiness and deadlines, the filter
model, the security cards, and desired state. `pymergetic.rxf.net.transport` is the
transport layer (§12): one stream contract, protocol modules over one codec each, TLS as
an optional wrapper no protocol knows about.

A readiness wait is a park of one run cell and the wake is a channel frame (docs/10) —
this layer owns state and the packet path, never a second scheduler or a second queue.
Everything mutable is a delta against a named base (docs/24): nothing here rewrites
history.
"""

